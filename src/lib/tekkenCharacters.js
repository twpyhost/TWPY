export const TEKKEN_CHARACTERS = NAMES.map((name) => ({
  key: name.toLowerCase().replaceAll(" ", "-"),
  name,
  portrait: `/images/personajes/${encodeURIComponent(name)}.${["Devil Jin", "Panda", "Reina"].includes(name) ? "png" : "webp"}`,
}));
export function getTekkenCharacter(key) {
  return TEKKEN_CHARACTERS.find((character) => character.key === key) ?? null;
}
